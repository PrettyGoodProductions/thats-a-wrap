"""Measures the batch 6 masters (Thats-A-Wrap-Approved-Assets-04.zip, the HQ set) and writes the batch map.

  python3 -I tools/make_batch6_map.py <unzipped folder>/assets tools/batch6.map.json
  python3 -I tools/prep_art.py tools/batch6.map.json <unzipped folder>/assets art
  python3 -I tools/audit_art.py art

(The project calls this zip "art batch 4"; in the repo it is batch 6.)

Fit rules. The art's own alpha sets the scale (bounding box at alpha 128, so faint haze never counts):
  rooms      opaque pictures of one 152 x 112 box. Each state is cropped to that aspect around its own box, so the
             rooms that came out slightly wider (1.43 against 1.36) lose a sliver at the sides instead of stretching
  for-rent   84 wide, hangs from the rope, pivot at the top center
  lobby      312 wide. It came 5.2 : 1 (spec 3.71 : 1), so it is 60 units tall instead of 84
  street     360 wide. It came 5.7 : 1 (spec 4.19 : 1), so it is 63 units tall instead of 86
  jobboard   116 wide as in the manifest. The lobby wall has no room for that size, so the game draws it smaller
  flyer      30 wide, pinned at the top center
  van        84 wide (the art is a boxy van with a roof rack, 1.39 : 1, not the 2.5 : 1 canvas the manifest drew)
  sky        360 wide, 6 px per unit as exported
  size       rooms, lobby, street and sky are fitted at 4 px per unit, not 6: the office shows 1 unit at about 1.2 CSS px, so 4 is
             about native on a 3x phone, and the 6 px version added 1.6 MB to a page that was already near the 6 MB warning
  clouds     64 and 36 wide
"""
import json, os, sys
import numpy as np
from PIL import Image

src, out = sys.argv[1:3]
NAMES = {int(f[:3]): f for f in sorted(os.listdir(src)) if f[:3].isdigit() and f.endswith('.png')}
CLOUDS = {f: f for f in os.listdir(src) if f.startswith('150-')}


def load(name):
    return np.array(Image.open(os.path.join(src, name)).convert('RGBA'))


def bbox(a, t=128):
    ys, xs = np.where(a[..., 3] > t)
    return int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1


pieces, info = {}, {}
RATIO = 152 / 112


def room_state(name):
    """Crop to the 152:112 aspect, centered on the art's own box"""
    x0, y0, x1, y1 = bbox(load(name))
    w, h = x1 - x0, y1 - y0
    if w / h > RATIO:
        nw = int(round(h * RATIO)); x0 += (w - nw) // 2; x1 = x0 + nw
    else:
        nh = int(round(w / RATIO)); y0 += (h - nh) // 2; y1 = y0 + nh
    return {'file': name, 'crop': [x0, y0, x1, y1], 'native': round((x1 - x0) / 152, 3), 'pivot': [0, 0]}


for room, states in {'edit': {'building': 133, 'built': 134}, 'craft': {'for-rent': 135, 'building': 136, 'built': 137},
                     'gear': {'for-rent': 138, 'building': 139, 'built': 140}, 'kitchen': {'for-rent': 141, 'building': 142, 'built': 143}}.items():
    files = {st: room_state(NAMES[n]) for st, n in states.items()}
    pieces[f'hq.room.{room}'] = {'native': 9.6, 'target': 4, 'pivot': [0, 0], 'files': files, 'quantize': 256, 'opaque': True}
    info[f'hq.room.{room}-px-per-unit'] = {st: f['native'] for st, f in files.items()}


def one(pid, name, width, pivot, target=6, margin=True, clean=False, **extra):
    a = load(name)
    x0, y0, x1, y1 = bbox(a)
    nat = (x1 - x0) / width
    px = {'tl': (0, 0), 'tc': ((x1 - x0) / 2, 0), 'bc': ((x1 - x0) / 2, y1 - y0)}[pivot]
    m = int(np.ceil(5 * nat / target)) + 1 if margin else 0   # about 5 export px of empty margin, except on full-bleed pictures
    cr = [x0 - m, y0 - m, x1 + m, y1 + m]
    ent = {'file': name, 'crop': cr}
    if clean: ent.update(decontaminate=True, alpha_floor=40)   # a faint halo around the art: drop the faint alpha and recolor the soft edge
    pieces[pid] = {'native': round(nat, 3), 'target': target, 'pivot': [px[0] + m, px[1] + m], 'files': {'default': ent}, **extra}
    info[pid] = f'{width} x {round((y1 - y0) / nat, 1)} units at {round(nat, 2)} px per unit'


one('hq.for-rent', NAMES[144], 84, 'tc', quantize=256)
one('hq.lobby', NAMES[145], 312, 'tl', target=4, margin=False, quantize=256, opaque=True)
one('hq.jobboard', NAMES[146], 116, 'tl', quantize=256)
one('hq.flyer', NAMES[147], 30, 'tc', quantize=256)
one('hq.street', NAMES[148], 360, 'tl', target=4, margin=False, quantize=256, opaque=True)
one('hq.van', NAMES[149], 84, 'bc', clean=True, quantize=256)
one('hq.cloud-small', CLOUDS['150-hq.cloud-small.png'], 36, 'tl', quantize=256)
one('hq.cloud-wide', CLOUDS['150-hq.cloud-wide.png'], 64, 'tl', quantize=256)
sky = [f for f in CLOUDS if 'sky' in f][0]
pieces['hq.sky'] = {'native': 6, 'target': 4, 'pivot': [0, 0], 'files': {'default': {'file': sky}}, 'quantize': 64, 'opaque': True}
info['hq.sky'] = '360 x 70 units, the export as delivered'

json.dump({'_note': 'Batch 6 (Nov 5): masters from Thats-A-Wrap-Approved-Assets-04.zip, the HQ set. Generated by tools/make_batch6_map.py.', 'info': info, 'pieces': pieces}, open(out, 'w'), indent=1, default=lambda o: o.item() if hasattr(o, 'item') else str(o))
print(json.dumps(info, indent=1))
