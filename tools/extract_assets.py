"""Cut usable pieces out of the approved concept art and write src/assets.js.

  python3 tools/extract_assets.py

Pieces: the THAT'S A WRAP! logo (background removed), three shot thumbnails, and a
neutral paper-grain tile used as a texture overlay on the set. Re-run after replacing refs/*.png.
"""
import base64, io
from PIL import Image, ImageDraw, ImageOps, ImageFilter

SHOOT = 'refs/concept-shoot.png'
OUT = 'src/assets.js'

def b64(img, fmt='WEBP', **kw):
    buf = io.BytesIO()
    img.save(buf, fmt, **kw)
    return f"data:image/{fmt.lower()};base64," + base64.b64encode(buf.getvalue()).decode()

im = Image.open(SHOOT).convert('RGB')

# Logo: keep the cream paper sticker and everything printed on it
logo = im.crop((10, 0, 186, 118)).convert('RGBA')
w, h = logo.size
px = logo.load()
mask = Image.new('L', (w, h), 0)
mp = mask.load()
for y in range(h):
    for x in range(w):
        r, g, b, _ = px[x, y]
        if r > 175 and g > 160 and b > 120 and r - b < 90:
            mp[x, y] = 255
# Fill the holes made by the dark lettering: flood the outside, invert
outside = mask.copy()
ImageDraw.floodfill(outside, (0, 0), 128)
ImageDraw.floodfill(outside, (w - 1, h - 1), 128)
ImageDraw.floodfill(outside, (0, h - 1), 128)
ImageDraw.floodfill(outside, (w - 1, 0), 128)
alpha = outside.point(lambda v: 0 if v == 128 else 255).filter(ImageFilter.MinFilter(3)).filter(ImageFilter.GaussianBlur(0.6))
logo.putalpha(alpha)
logo = logo.resize((w * 2, h * 2), Image.LANCZOS)

thumbs = {
    'hero': im.crop((1313, 193, 1430, 298)),
    'cheese': im.crop((1313, 331, 1430, 434)),
    'sauce': im.crop((1313, 471, 1430, 574)),
}

# Paper grain: the white foam board, flattened to mid-gray so it can multiply over any color
grain = im.crop((372, 245, 452, 315))
grain = ImageOps.grayscale(grain)
grain = ImageOps.autocontrast(grain, cutoff=2)
blur = grain.filter(ImageFilter.GaussianBlur(12))
diff = Image.new('L', grain.size)
gp, bp, dp = grain.load(), blur.load(), diff.load()
for y in range(grain.size[1]):
    for x in range(grain.size[0]):
        dp[x, y] = max(0, min(255, 200 + (gp[x, y] - bp[x, y])))
grain = diff

with open(OUT, 'w') as f:
    f.write('/* Generated by tools/extract_assets.py from the approved concept art. Do not edit by hand. */\n')
    f.write('(function (root) {\n  root.WrapAssets = {\n')
    f.write(f"    logo: '{b64(logo, 'WEBP', quality=88)}',\n")
    f.write("    thumbs: {\n")
    for k, t in thumbs.items():
        f.write(f"      {k}: '{b64(t.resize((t.width * 2, t.height * 2), Image.LANCZOS), 'WEBP', quality=86)}',\n")
    f.write("    },\n")
    f.write(f"    grain: '{b64(grain, 'PNG')}',\n")
    f.write('  };\n})(typeof globalThis !== "undefined" ? globalThis : this);\n')
print('wrote', OUT)
